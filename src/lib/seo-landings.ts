const bySlug = new Map(SEO_LANDINGS.map((l) => [l.slug, l]));

export function getSeoLanding(slug: string): SeoLanding | undefined {
  return bySlug.get(slug);
}

export function seoLandingPath(slug: string): string {
  return `/zakaz/${slug}/`;
}

export function seoLandingCanonical(slug: string): string {
  return `${SITE_URL}${seoLandingPath(slug)}`;
}
